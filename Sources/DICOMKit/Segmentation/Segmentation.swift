        seriesInstanceUID: String,
        studyInstanceUID: String,
        instanceNumber: Int? = nil,
        seriesNumber: Int? = nil,
        contentLabel: String? = nil,
        contentDescription: String? = nil,
        contentCreatorName: DICOMPersonName? = nil,
        contentDate: DICOMDate? = nil,
        contentTime: DICOMTime? = nil,
        segmentationType: SegmentationType,
        segmentationFractionalType: SegmentationFractionalType? = nil,
        maxFractionalValue: Int? = nil,
        segmentsOverlap: SegmentsOverlap? = nil,
        pixelPaddingValue: Int? = nil,
        numberOfSegments: Int,
        segments: [Segment],
        frameOfReferenceUID: String? = nil,
        dimensionOrganizationUID: String? = nil,
        referencedSeries: [SegmentationReferencedSeries] = [],
        numberOfFrames: Int,
        rows: Int,
        columns: Int,
        bitsAllocated: Int,
        bitsStored: Int,
        highBit: Int,
        samplesPerPixel: Int = 1,
        photometricInterpretation: String = "MONOCHROME2",
        pixelRepresentation: Int = 0,
        sharedFunctionalGroups: FunctionalGroup? = nil,
        perFrameFunctionalGroups: [FunctionalGroup] = [],
        paletteColorLookupTable: PaletteColorLUT? = nil,
        iccProfile: Data? = nil,
        colorSpace: String? = nil
    ) {
        self.sopInstanceUID = sopInstanceUID
        self.sopClassUID = sopClassUID ?? Segmentation.sopClassUID(for: segmentationType)
        self.seriesInstanceUID = seriesInstanceUID
        self.studyInstanceUID = studyInstanceUID
        self.instanceNumber = instanceNumber
        self.seriesNumber = seriesNumber
        self.contentLabel = contentLabel
        self.contentDescription = contentDescription
        self.contentCreatorName = contentCreatorName
        self.contentDate = contentDate
        self.contentTime = contentTime
        self.segmentationType = segmentationType
        self.segmentationFractionalType = segmentationFractionalType
        self.maxFractionalValue = maxFractionalValue
        self.segmentsOverlap = segmentsOverlap
        self.pixelPaddingValue = pixelPaddingValue
        self.numberOfSegments = numberOfSegments
        self.segments = segments
        self.frameOfReferenceUID = frameOfReferenceUID
        self.dimensionOrganizationUID = dimensionOrganizationUID
        self.referencedSeries = referencedSeries
        self.numberOfFrames = numberOfFrames
        self.rows = rows
        self.columns = columns
        self.bitsAllocated = bitsAllocated
        self.bitsStored = bitsStored
        self.highBit = highBit
        self.samplesPerPixel = samplesPerPixel
        self.photometricInterpretation = photometricInterpretation
        self.pixelRepresentation = pixelRepresentation
        self.sharedFunctionalGroups = sharedFunctionalGroups
        self.perFrameFunctionalGroups = perFrameFunctionalGroups
        self.paletteColorLookupTable = paletteColorLookupTable
        self.iccProfile = iccProfile
        self.colorSpace = colorSpace
    }
}

// MARK: - SegmentationType

/// Type of segmentation encoding — Segmentation Type (0062,0001), Enumerated Values
/// BINARY, FRACTIONAL, LABELMAP
///
/// Reference: PS3.3 Table C.8.20-2 and C.8.20.2.3 - Segmentation Image Module
public enum SegmentationType: String, Sendable, Codable, CaseIterable {
    /// BINARY: the segmented property is present with a pixel value of 1 and absent with 0
    /// (C.8.20.2.3.1). Bits Allocated 1, one frame per segment and slice.
    case binary = "BINARY"

    /// FRACTIONAL: the segmented property is a value from 0 to Maximum Fractional Value
    /// (0062,000E), qualified by Segmentation Fractional Type (C.8.20.2.3.2). Bits Allocated 8.
    case fractional = "FRACTIONAL"

    /// LABELMAP: the presence of the segmented property is conveyed by the integer pixel
    /// value, which is one of the Segment Number (0062,0004) values; every pixel value
    /// actually encoded must be described by a Segment Sequence Item (C.8.20.2.3.3).
    /// Bits Allocated 8 or 16, Photometric Interpretation MONOCHROME2 or PALETTE COLOR, one
    /// frame per slice, no Segmentation Functional Group (Table A.51-2).
    case labelmap = "LABELMAP"

    /// Photometric Interpretation (0028,0004) Enumerated Values for this type (Table C.8.20-2)
    public var allowedPhotometricInterpretations: [String] {
        switch self {
        case .binary, .fractional: return ["MONOCHROME2"]
        case .labelmap: return ["MONOCHROME2", "PALETTE COLOR"]
        }
    }

    /// Bits Allocated (0028,0100) Enumerated Values for this type (Table C.8.20-2)
    public var allowedBitsAllocated: [Int] {
        switch self {
        case .binary: return [1]
        case .fractional: return [8]
        case .labelmap: return [8, 16]
        }
    }
}

// MARK: - SegmentsOverlap

/// Segments Overlap (0062,0013): whether any pixel is or might be in more than one Segment
///
/// Reference: PS3.3 Table C.8.20-2 and C.8.20.2.3
public enum SegmentsOverlap: String, Sendable, Codable, CaseIterable {
    /// Some Segments overlap
    case yes = "YES"
    /// Some Segments might overlap
    case undefined = "UNDEFINED"
    /// No Segments overlap (the only value allowed for LABELMAP)
    case no = "NO"
}

