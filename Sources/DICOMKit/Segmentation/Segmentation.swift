/// DICOM Segmentation IOD
///
/// A Segmentation object contains labeled image regions representing anatomical structures,
/// pathological regions, or other areas of interest. Segmentations can be binary (presence/absence),
/// fractional (probability values) or a label map (one frame per slice whose pixel value is the
/// Segment Number) and are commonly generated by AI/ML algorithms or manual annotation tools.
///
/// Reference: PS3.3 A.51 - Segmentation IOD
/// Reference: PS3.3 C.8.20 - Segmentation Modules
/// Reference: PS3.4 B.5.1.25 - Segmentation Storage SOP Classes
public struct Segmentation: Sendable {

    // MARK: - SOP Class UIDs (PS3.6 Table A-1)

    /// Segmentation Storage — Segmentation Type BINARY or FRACTIONAL (PS3.4 B.5.1.25)
    public static let segmentationStorageUID = "1.2.840.10008.5.1.4.1.1.66.4"

    /// Label Map Segmentation Storage — Segmentation Type LABELMAP (PS3.4 B.5.1.25)
    public static let labelMapSegmentationStorageUID = "1.2.840.10008.5.1.4.1.1.66.7"

    /// The SOP Class UID PS3.4 B.5.1.25 assigns to a Segmentation Type
    public static func sopClassUID(for segmentationType: SegmentationType) -> String {
        switch segmentationType {
        case .binary, .fractional: return segmentationStorageUID
        case .labelmap: return labelMapSegmentationStorageUID
        }
    }

    // MARK: - Segmentation Identification

    /// SOP Instance UID
    public let sopInstanceUID: String

    /// SOP Class UID: Segmentation Storage (1.2.840.10008.5.1.4.1.1.66.4) for BINARY and
    /// FRACTIONAL, Label Map Segmentation Storage (1.2.840.10008.5.1.4.1.1.66.7) for LABELMAP
    public let sopClassUID: String
    
    /// Series Instance UID
    public let seriesInstanceUID: String
    
    /// Study Instance UID
    public let studyInstanceUID: String
    
    /// Instance Number
    public let instanceNumber: Int?

    /// Series Number (0020,0011), Type 1 in the Segmentation Series Module (Table C.8.20-1)
    public let seriesNumber: Int?

    /// Content Label - a label that identifies the content
    public let contentLabel: String?
    
    /// Content Description - human-readable description
    public let contentDescription: String?
    
    /// Content Creator's Name
    public let contentCreatorName: DICOMPersonName?
    
    /// Content Date
    public let contentDate: DICOMDate?
    
    /// Content Time
    public let contentTime: DICOMTime?
    
    // MARK: - Segmentation Type and Properties
    
    /// Type of segmentation (BINARY, FRACTIONAL or LABELMAP)
    public let segmentationType: SegmentationType

    /// Segmentation fractional type (only for FRACTIONAL)
    public let segmentationFractionalType: SegmentationFractionalType?

    /// Maximum fractional value (only for FRACTIONAL)
    public let maxFractionalValue: Int?

    /// Segments Overlap (0062,0013), Type 3. "If present, shall be NO if Segmentation
    /// Type (0062,0001) is LABELMAP" (PS3.3 Table C.8.20-2).
    public let segmentsOverlap: SegmentsOverlap?

    /// Pixel Padding Value (0028,0120): for a LABELMAP, the Segment Number treated as
    /// background (PS3.3 A.51.4, C.8.20.2.4, C.7.5.1.1.2). Shall not be present unless
    /// Segmentation Type is LABELMAP.
    public let pixelPaddingValue: Int?

    /// Number of segments
    public let numberOfSegments: Int
    
    /// Segment sequence - definitions of all segments
    public let segments: [Segment]
    
    // MARK: - Image Reference
    
    /// Frame of Reference UID
    public let frameOfReferenceUID: String?
    
    /// Dimension Organization UID
    public let dimensionOrganizationUID: String?
    
    /// Referenced Series Sequence
    public let referencedSeries: [SegmentationReferencedSeries]
    
    // MARK: - Pixel Data Properties
    
    /// Number of frames
    public let numberOfFrames: Int
    
    /// Rows
    public let rows: Int
    
    /// Columns
    public let columns: Int
    
    /// Bits Allocated
    public let bitsAllocated: Int
    
    /// Bits Stored
    public let bitsStored: Int
    
    /// High Bit
    public let highBit: Int
    
    /// Samples Per Pixel
    public let samplesPerPixel: Int
    
    /// Photometric Interpretation
    public let photometricInterpretation: String
    
    /// Pixel Representation (0 = unsigned, 1 = signed)
    public let pixelRepresentation: Int
    
    // MARK: - Functional Groups
    
    /// Shared Functional Groups Sequence
    public let sharedFunctionalGroups: FunctionalGroup?
    
    /// Per-Frame Functional Groups Sequence
    public let perFrameFunctionalGroups: [FunctionalGroup]

    // MARK: - PALETTE COLOR (LABELMAP only)

    /// Palette Color Lookup Table Module (PS3.3 2026a C.7.9, Table C.7-22a), which the
    /// Segmentation IOD requires "if Photometric Interpretation (0028,0004) has a Value of
    /// PALETTE COLOR" (Table A.51-1). PALETTE COLOR is allowed only for LABELMAP
    /// (Table C.8.20-2); the table is indexed by the stored pixel value, i.e. the Segment
    /// Number. `nil` for MONOCHROME2: a Conditional Module whose condition is not met
    /// "shall not be present" (A.1.3.2).
    public let paletteColorLookupTable: PaletteColorLUT?

    /// ICC Profile (0028,2000) of the ICC Profile Module (C.11.15, Table C.11.15-1), which
    /// the Segmentation IOD requires with PALETTE COLOR (Table A.51-1). The profile must be
    /// an Input Device ("scnr") RGB profile with a Lab or XYZ PCS (C.11.15.1.1).
    public let iccProfile: Data?

    /// Color Space (0028,2002), Type 3 in the ICC Profile Module (C.11.15.1.2 Defined
    /// Terms SRGB, ADOBERGB, ROMMRGB, DISPLAYP3)
    public let colorSpace: String?

    // MARK: - Patient, General Study and Enhanced General Equipment (Table A.51-1)

    /// The Type 2 attributes of the Patient (PS3.3 2026a Table C.7-1) and General Study
    /// (Table C.7-3) Modules, both M in Table A.51-1; written by `buildDataSet`, zero length
    /// when unknown. `SegmentationBuilder.setPatientAndStudy(_:)` sets it.
    public var patientAndStudy = SegmentationPatientAndStudy()

    /// The Enhanced General Equipment Module (Table A.51-1, M; Table C.7-8b, all Type 1),
    /// written by `buildDataSet`; it also supplies Manufacturer (0008,0070) of the General
    /// Equipment Module. `SegmentationBuilder.setEquipment(_:)` sets it.
    public var equipment = SegmentationEquipment.dicomKit
    
    // MARK: - Initialization
    
    /// Initialize a Segmentation
    ///
    /// `sopClassUID` defaults to the SOP Class PS3.4 B.5.1.25 assigns to `segmentationType`.
    public init(
        sopInstanceUID: String,
