#!/usr/bin/env python3
"""Generate the allocation-free primary-VR projection of the maintained dictionary."""
from pathlib import Path
import argparse
import hashlib

root = Path(__file__).resolve().parent.parent
source = root / 'Sources/DICOMDictionary/Resources/DataElementDictionary.txt'
target = root / 'Sources/DICOMDictionary/PrimaryValueRepresentation.swift'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
rows = {}
for line in source.read_text().splitlines():
    if line.startswith('#'):
        continue
    fields = line.split('|', 6)
    if len(fields) < 6:
        continue
    try:
        group, element = int(fields[0], 16), int(fields[1], 16)
    except ValueError:
        continue
    # Same first-valid-VR/UN rule as DataElementDictionary.entries.
    known = {'AE','AS','AT','CS','DA','DS','DT','FD','FL','IS','LO','LT','OB','OD','OF','OL','OV','OW','PN','SH','SL','SQ','SS','ST','SV','TM','UC','UI','UL','UN','UR','US','UT','UV'}
    vr = next((vr for vr in fields[4].split('/') if vr in known), 'UN')
    rows[(group, element)] = vr
lines = [
    '// Generated by Scripts/generate_primary_vr.py; do not edit by hand.',
    '// NEMA-verified: 2026a, checked 2026-10-14 — exact primary-VR projection of the maintained PS3.6 dictionary resource.',
    '// Source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
    'import DICOMCore', '', 'extension DataElementDictionary {',
    '    /// Primary VR without constructing the descriptive dictionary, strings or arrays.',
    '    /// Uses the same repeating-group canonicalization and first-VR/UN policy',
    '    /// as lookup(tag:). The authoritative data remains the bundled dictionary.',
    '    public static func primaryValueRepresentation(for tag: Tag) -> VR? {',
    '        let canonical = canonicalTag(tag)',
    '        switch canonical.group {'
]
for group in sorted({group for group, _ in rows}):
    lines += [f'        case 0x{group:04X}:', '            switch canonical.element {']
    for vr in sorted({vr for (g, _), vr in rows.items() if g == group}):
        elements = [f'0x{element:04X}' for (g, element), value in sorted(rows.items()) if g == group and value == vr]
        # Small source lines; each case has a scalar result, no collection literal.
        for offset in range(0, len(elements), 8):
            lines.append('            case ' + ', '.join(elements[offset:offset + 8]) + f': return .{vr}')
    lines += ['            default: return nil', '            }']
lines += ['        default: return nil', '        }', '    }', '}', '']
text = '\n'.join(lines)
if args.check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Generated primary VR lookup is stale; run Scripts/generate_primary_vr.py')
else:
    target.write_text(text)
print(f'Primary VR projection: {len(rows)} entries; {"verified" if args.check else "generated"}.')
